// Checks that the spark_dsg observer patch reports every node and edge change: a graph is
// built and edited the ways Hydra's backend does (mergeGraph, removeNode, mergeNodes,
// removeEdge, clear) and after each step Yggdrasil, fed only the reported operations, must
// equal spark_dsg.
//
//   ros2 run hydra_ygg_sink observer_check <dsg.json>     (any Hydra backend export)
#include <spark_dsg/dynamic_scene_graph.h>
#include <spark_dsg/graph_observer.h>
#include <spark_dsg/serialization/graph_json_serialization.h>

#include <fstream>
#include <iostream>
#include <random>
#include <sstream>
#include <vector>

#include "ygg_bridge_cxx/lib.h"  // generated by corrosion_add_cxxbridge

using namespace spark_dsg;

struct Recorder : GraphObserver {
  std::vector<hydra_ygg::GraphOp> ops;
  void nodeAdded(NodeId n) override { ops.push_back({0, n, 0}); }
  void nodeRemoved(NodeId n) override { ops.push_back({1, n, 0}); }
  void edgeAdded(NodeId s, NodeId t) override { ops.push_back({2, s, t}); }
  void edgeRemoved(NodeId s, NodeId t) override { ops.push_back({3, s, t}); }
  void cleared() override { ops.push_back({4, 0, 0}); }
};

int main(int argc, char** argv) {
  if (argc < 2) {
    std::cerr << "usage: observer_check <dsg.json>" << std::endl;
    return 2;
  }
  const auto source = DynamicSceneGraph::load(argv[1]);
  DynamicSceneGraph graph;
  Recorder recorder;
  graph.setObserver(&recorder);
  auto mirror = hydra_ygg::new_mirror();
  bool ok = true;

  auto step = [&](const std::string& what) {
    const auto json = io::json::writeGraph(graph, false);
    const auto s =
        mirror->apply_ops(json, rust::Slice<const hydra_ygg::GraphOp>(recorder.ops.data(),
                                                                      recorder.ops.size()));
    recorder.ops.clear();
    const auto r = mirror->compare_with(json, 1e-5);
    std::cout << what << ": ops=" << s.ops << " nodes=" << graph.numNodes()
              << " edges=" << graph.numEdges() << (r.equal ? " MATCH" : " DIFFER") << std::endl;
    if (!r.equal || s.unknown) {
      std::cout << std::string(r.summary) << " unknown=" << s.unknown << std::endl;
      ok = false;
    }
  };

  graph.mergeGraph(*source);
  step("mergeGraph");

  std::mt19937 rng(7);
  std::vector<NodeId> ids;
  for (const auto& [lid, layer] : graph.layers()) {
    for (const auto& [id, node] : layer->nodes()) ids.push_back(id);
  }
  std::shuffle(ids.begin(), ids.end(), rng);
  for (size_t i = 0; i < 100 && i < ids.size(); ++i) graph.removeNode(ids[i]);
  step("removeNode x100");

  size_t merged = 0;
  for (const auto& [lid, layer] : graph.layers()) {
    std::vector<NodeId> layer_ids;
    for (const auto& [id, node] : layer->nodes()) layer_ids.push_back(id);
    for (size_t i = 0; i + 1 < layer_ids.size() && i < 40; i += 2) {
      merged += graph.mergeNodes(layer_ids[i], layer_ids[i + 1]);
    }
  }
  step("mergeNodes x" + std::to_string(merged));

  std::vector<std::pair<NodeId, NodeId>> edges;
  for (const auto& [lid, layer] : graph.layers()) {
    for (const auto& [key, edge] : layer->edges()) edges.emplace_back(edge.source, edge.target);
  }
  for (size_t i = 0; i < edges.size(); i += 7) graph.removeEdge(edges[i].first, edges[i].second);
  step("removeEdge");

  graph.mergeGraph(*source);  // re-adds what was removed, as the backend does each update
  step("mergeGraph again");

  graph.clear();
  graph.mergeGraph(*source);
  step("clear + mergeGraph");

  std::cout << (ok ? "OBSERVER OK" : "OBSERVER FAILED") << std::endl;
  return ok ? 0 : 1;
}
