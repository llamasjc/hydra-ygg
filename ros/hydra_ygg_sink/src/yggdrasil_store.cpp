using Clock = std::chrono::steady_clock;

size_t envSize(const char* name, size_t fallback) {
  const char* value = std::getenv(name);
  return value ? std::stoul(value) : fallback;
}

double msSince(Clock::time_point start) {
  return std::chrono::duration<double, std::milli>(Clock::now() - start).count();
}

//! A graph as typed records: the same framing spark_dsg's binary writer uses, split per node
//! and edge so each can be stored and compared on its own.
struct Encoded {
  uint64_t timestamp_ns = 0;
  std::vector<uint8_t> header;
  std::vector<NodeRecord> nodes;
  std::vector<uint8_t> node_bytes;
  std::vector<EdgeRecord> edges;
  std::vector<uint8_t> edge_bytes;
};

void encodeNode(const SceneGraphNode& node, Encoded& out) {
  const size_t start = out.node_bytes.size();
  BinarySerializer s(&out.node_bytes);
  s.startFixedArray(4);
  s.write(node.layer.layer);
  s.write(node.id);
  s.write(node.layer.partition);
  s.write(node.attributes());

  const auto& attrs = node.attributes();
  const auto* semantic = dynamic_cast<const spark_dsg::SemanticNodeAttributes*>(&attrs);
  NodeRecord r;
  r.id = node.id;
  r.layer_key = static_cast<int64_t>(node.layer.layer) * 1000 + node.layer.partition;
  r.has_pos = true;
  r.x = attrs.position.x();
  r.y = attrs.position.y();
  r.z = attrs.position.z();
  r.has_label = semantic != nullptr;
  r.label = semantic ? semantic->semantic_label : 0;
  r.offset = start;
  r.len = out.node_bytes.size() - start;
  out.nodes.push_back(r);
}

void encodeEdge(const SceneGraphEdge& edge, Encoded& out) {
  const size_t start = out.edge_bytes.size();
  BinarySerializer s(&out.edge_bytes);
  s.startFixedArray(3);
  s.write(edge.source);
  s.write(edge.target);
  s.write(*edge.info);
  out.edges.push_back(EdgeRecord{edge.source, edge.target, start, out.edge_bytes.size() - start});
}

size_t encodeThreads() {
  static const size_t n = [] {
    const size_t hw = std::max(1u, std::thread::hardware_concurrency());
    return envSize("HYDRA_YGG_THREADS", std::min<size_t>(8, hw));
  }();
  return n;
}

//! Encode the whole graph. Nodes and edges are independent, so they are split across threads, each
//! filling its own buffer; the buffers are then joined and the offsets shifted.
Encoded encode(const DynamicSceneGraph& graph) {
  Encoded out;
  BinarySerializer h(&out.header);
  h.write(graph.layer_keys());
  h.write(spark_dsg::serialization::AttributeRegistry<spark_dsg::NodeAttributes>::names());
  h.write(spark_dsg::serialization::AttributeRegistry<spark_dsg::EdgeAttributes>::names());
  h.write(graph.layer_names());
  h.write(graph.metadata().dump());

  std::vector<const SceneGraphNode*> nodes;
  std::vector<const SceneGraphEdge*> edges;
  nodes.reserve(graph.numNodes());
  edges.reserve(graph.numEdges());
  for (const auto& [layer_id, layer] : graph.layers()) {
    for (const auto& [id, node] : layer->nodes()) {
      nodes.push_back(node.get());
    }
    for (const auto& [key, edge] : layer->edges()) {
      edges.push_back(&edge);
    }
  }
  for (const auto& [layer_id, partitions] : graph.layer_partitions()) {
    for (const auto& [partition_id, partition] : partitions) {
      for (const auto& [id, node] : partition->nodes()) {
        nodes.push_back(node.get());
      }
      for (const auto& [key, edge] : partition->edges()) {
        edges.push_back(&edge);
      }
    }
  }
  for (const auto& [key, edge] : graph.interlayer_edges()) {
    edges.push_back(&edge);
  }

  // Small graphs are not worth the threads.
  const size_t threads = nodes.size() < 512 ? 1 : encodeThreads();
  std::vector<Encoded> parts(threads);
  const size_t per_node = (nodes.size() + threads - 1) / threads;
  const size_t per_edge = (edges.size() + threads - 1) / threads;
  auto work = [&](size_t t) {
    for (size_t i = t * per_node; i < std::min(nodes.size(), (t + 1) * per_node); ++i) {
      encodeNode(*nodes[i], parts[t]);
    }
    for (size_t i = t * per_edge; i < std::min(edges.size(), (t + 1) * per_edge); ++i) {
      encodeEdge(*edges[i], parts[t]);
    }
  };
  std::vector<std::thread> pool;
  for (size_t t = 1; t < threads; ++t) {
    pool.emplace_back(work, t);
  }
  work(0);
  for (auto& th : pool) {
    th.join();
  }

  out.nodes.reserve(nodes.size());
  out.edges.reserve(edges.size());
  for (auto& part : parts) {
    const size_t node_shift = out.node_bytes.size();
    for (auto r : part.nodes) {
      r.offset += node_shift;
      out.nodes.push_back(r);
    }
    out.node_bytes.insert(out.node_bytes.end(), part.node_bytes.begin(), part.node_bytes.end());
    const size_t edge_shift = out.edge_bytes.size();
    for (auto r : part.edges) {
      r.offset += edge_shift;
      out.edges.push_back(r);
    }
    out.edge_bytes.insert(out.edge_bytes.end(), part.edge_bytes.begin(), part.edge_bytes.end());
  }
  return out;
}

//! Rebuild a spark_dsg graph from what Yggdrasil holds, through spark_dsg's binary reader.
DynamicSceneGraph::Ptr readBack(const TypedStore& store) {
  std::vector<uint8_t> buffer;
  const auto header = store.header();
  buffer.insert(buffer.end(), header.begin(), header.end());
  BinarySerializer s(&buffer);
  s.startDynamicArray();
  const auto nodes = store.node_records();
  buffer.insert(buffer.end(), nodes.begin(), nodes.end());
  s.endDynamicArray();
  s.startDynamicArray();
  const auto edges = store.edge_records();
  buffer.insert(buffer.end(), edges.begin(), edges.end());
  s.endDynamicArray();
  s.write(false);  // no mesh
  return spark_dsg::io::binary::readGraph(buffer);
}

//! Node and edge records of a graph by id, for comparing two graphs exactly.
struct Records {
  std::map<NodeId, std::vector<uint8_t>> nodes;
  std::map<std::pair<NodeId, NodeId>, std::vector<uint8_t>> edges;
};

Records records(const DynamicSceneGraph& graph) {
  const auto e = encode(graph);
  Records r;
  for (const auto& n : e.nodes) {
    r.nodes[n.id].assign(e.node_bytes.begin() + n.offset,
                         e.node_bytes.begin() + n.offset + n.len);
  }
  for (const auto& x : e.edges) {
    const auto key = std::minmax(x.source, x.target);
    r.edges[key].assign(e.edge_bytes.begin() + x.offset,
                        e.edge_bytes.begin() + x.offset + x.len);
  }
  return r;
}

//! Empty when equal, otherwise what differs.
template <typename Map>
void diff(const char* what, const Map& want, const Map& got, std::ostringstream& out) {
  size_t missing = 0, extra = 0, changed = 0;
  for (const auto& [k, v] : want) {
    const auto it = got.find(k);
    if (it == got.end()) {
      ++missing;
    } else if (it->second != v) {
      ++changed;
    }
  }
  for (const auto& [k, v] : got) {
    extra += want.count(k) ? 0 : 1;
  }
  if (missing || extra || changed) {
    out << what << " missing=" << missing << " extra=" << extra << " changed=" << changed << " ";
  }
}

std::string compare(const DynamicSceneGraph& want, const DynamicSceneGraph& got) {
  const auto a = records(want);
  const auto b = records(got);
  std::ostringstream out;
  diff("nodes", a.nodes, b.nodes, out);
  diff("edges", a.edges, b.edges, out);
  return out.str();
}

class YggdrasilStore : public hydra::GraphStore {
 public:
  explicit YggdrasilStore(const std::string& mode)
      : publish_yggdrasil_(mode == "yggdrasil"),
        compare_every_(envSize("HYDRA_YGG_COMPARE_EVERY", 10)) {
    if (mode != "yggdrasil" && mode != "both") {
      throw std::invalid_argument("HYDRA_GRAPH_BACKEND must be spark, yggdrasil or both, not " +
                                  mode);
    }
    // std::cerr, not glog: Hydra's glog setup hides INFO from the launch output.
    std::cerr << "[YggdrasilStore] mode=" << mode << " (typed records)" << std::endl;
    if (const char* path = std::getenv("HYDRA_YGG_RECORD")) {
      store_->record_to(path);
      std::cerr << "[YggdrasilStore] recording deltas to " << path << std::endl;
    }
  }

  void attach(DynamicSceneGraph&) override {}

  //! The store once any background apply has finished.
  const TypedStore& typed() const {
    wait();
    return *store_;
  }

  ~YggdrasilStore() override { wait(); }

  DynamicSceneGraph::Ptr store(uint64_t timestamp_ns, const DynamicSceneGraph& graph) override {
    const auto t0 = Clock::now();
    auto e = std::make_shared<Encoded>(encode(graph));
    e->timestamp_ns = timestamp_ns;
    const double encode_ms = msSince(t0);
    ++updates_;
    const bool compare_now = compare_every_ > 0 && updates_ % compare_every_ == 0;

    // The previous apply has almost always finished by now; Yggdrasil takes one at a time.
    wait();
    if (!publish_yggdrasil_ && !compare_now) {
      // Nothing below needs Yggdrasil yet, so Hydra does not wait for the apply.
      pending_ = std::async(std::launch::async, [this, e, encode_ms, n = updates_] {
        std::cerr << line(n, apply(*e), encode_ms) + " (background)\n";
      });
      return nullptr;
    }

    std::cerr << line(updates_, apply(*e), encode_ms);
    DynamicSceneGraph::Ptr output;
    if (publish_yggdrasil_) {
      const auto t1 = Clock::now();
      output = readBack(*store_);
      output->setMesh(graph.mesh());
      std::cerr << " readback=" << msSince(t1) << "ms";
    }
    if (compare_now) {
      const auto back = output ? output : readBack(*store_);
      const auto d = compare(graph, *back);
      std::cerr << (d.empty() ? " | matches spark_dsg" : " | DIFFERS from spark_dsg: " + d);
    }
    std::cerr << std::endl;
    return output;
  }

  void save(const std::filesystem::path& dir) const override {
    wait();
    const auto back = readBack(*store_);
    std::ofstream(dir / "dsg_from_yggdrasil.json") << spark_dsg::io::json::writeGraph(*back, false);
    std::cerr << "[YggdrasilStore] saved to " << dir << std::endl;
  }

 private:
  void wait() const {
    if (pending_.valid()) {
      pending_.get();
    }
  }

  TypedStats apply(const Encoded& e) {
    store_->set_time(e.timestamp_ns);
    return store_->apply(
        rust::Slice<const uint8_t>(e.header.data(), e.header.size()),
        rust::Slice<const NodeRecord>(e.nodes.data(), e.nodes.size()),
        rust::Slice<const uint8_t>(e.node_bytes.data(), e.node_bytes.size()),
        rust::Slice<const EdgeRecord>(e.edges.data(), e.edges.size()),
        rust::Slice<const uint8_t>(e.edge_bytes.data(), e.edge_bytes.size()));
  }

  static std::string line(size_t n, const TypedStats& s, double encode_ms) {
    std::ostringstream out;
    out << "[YggdrasilStore] update " << n << " nodes=" << s.nodes << "(+" << s.nodes_added
        << " ~" << s.nodes_updated << " -" << s.nodes_removed << ") edges=" << s.edges << "(+"
        << s.edges_added << " ~" << s.edges_updated << " -" << s.edges_removed
        << ") encode=" << encode_ms << "ms apply=" << s.apply_us / 1000.0 << "ms";
    return out.str();
  }

  const bool publish_yggdrasil_;
  const size_t compare_every_;
  size_t updates_ = 0;
  rust::Box<TypedStore> store_ = new_typed_store();
  mutable std::future<void> pending_;
};

const bool registered = [] {
  hydra::GraphStore::factory() = [](const std::string& mode) -> hydra::GraphStore::Ptr {
    return std::make_unique<YggdrasilStore>(mode);
  };
  return true;
}();

