// Yggdrasil storage for Hydra's backend scene graph.
//
// Needs the patches in patches/hydra. Loaded into hydra_ros_node with LD_PRELOAD and selected
// with HYDRA_GRAPH_BACKEND:
//   yggdrasil  the backend keeps a copy of its graph in Yggdrasil, and everything downstream
//              (ROS publisher, visualizer, sinks) receives the graph read back out of Yggdrasil
//   both       spark_dsg stays the published graph, Yggdrasil is kept alongside and the two
//              are compared every HYDRA_YGG_COMPARE_EVERY updates (default 10)
// With HYDRA_YGG_RECORD=<file>, every update's delta (only what changed) is appended to that
// file, one JSON line per update, for the Hydra-Multi station to replay (crates/station).
//
// Each update copies the graph into Yggdrasil as typed records, with no JSON: per node its id,
// layer, position and semantic label, plus spark_dsg's own binary encoding of the node so the
// graph can be rebuilt exactly. Hydra edits node attributes in place, so every node is
// encoded each update; Yggdrasil only changes for nodes whose encoding changed.
